/// slug と言語コードからシード表示名を解決。未対応言語は en→ja でフォールバック。
String seedCategoryName(String slug, String langCode) {
  return _seedNames[langCode]?[slug] ??
      _seedNames['en']![slug] ??
      _seedNames['ja']![slug] ??
      slug;
}

